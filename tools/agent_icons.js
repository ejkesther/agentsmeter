#!/usr/bin/env node
// Corner icons for the agents that aren't Claude (firmware/src/agent_icons.h).
// Original pixel art on the corner Clawd's 24x16-cell grid, drawn at his
// sizes: 3 px/cell (72x48) and 2 px/cell (48x32), so either one sits in his
// seat exactly. Output is LVGL RGB565A8 like clawd_still.h.
//
//   node tools/agent_icons.js            # rewrites firmware/src/agent_icons.h
'use strict';
const fs = require('fs');
const path = require('path');

const COLS = 24, ROWS = 16;

// Codex: a terminal window with its `>_` prompt.
const CODEX = {
  palette: { O: 0xc8cdd4, F: 0x2a2f37, W: 0xffffff },
  rows: [
    '........................',
    '..OOOOOOOOOOOOOOOOOOOO..',
    '.OFFFFFFFFFFFFFFFFFFFFO.',
    '.OFFFFFFFFFFFFFFFFFFFFO.',
    '.OFFWWFFFFFFFFFFFFFFFFO.',
    '.OFFFWWFFFFFFFFFFFFFFFO.',
    '.OFFFFWWFFFFFFFFFFFFFFO.',
    '.OFFFFFWWFFFFFFFFFFFFFO.',
    '.OFFFFWWFFFFFFFFFFFFFFO.',
    '.OFFFWWFFFFFFFFFFFFFFFO.',
    '.OFFWWFFFFWWWWWWFFFFFFO.',
    '.OFFFFFFFFFFFFFFFFFFFFO.',
    '.OFFFFFFFFFFFFFFFFFFFFO.',
    '.OFFFFFFFFFFFFFFFFFFFFO.',
    '..OOOOOOOOOOOOOOOOOOOO..',
    '........................',
  ],
};

// Cursor: a mouse pointer.
const CURSOR = {
  palette: { K: 0x7d838c, W: 0xf5f5f5 },
  rows: [
    '.......K................',
    '.......KK...............',
    '.......KWK..............',
    '.......KWWK.............',
    '.......KWWWK............',
    '.......KWWWWK...........',
    '.......KWWWWWK..........',
    '.......KWWWWWWK.........',
    '.......KWWWWWWWK........',
    '.......KWWWWWWWWK.......',
    '.......KWWWWWKKKKK......',
    '.......KWWKWWK..........',
    '.......KWK.KWWK.........',
    '.......KK..KWWK.........',
    '............KWWK........',
    '.............KK.........',
  ],
};

function rgb565(c) {
  const r = (c >> 16) & 0xff, g = (c >> 8) & 0xff, b = c & 0xff;
  return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3);
}

// RGB565A8 at `cell` px per grid cell: w*h little-endian RGB565 pixels,
// then w*h alpha bytes.
function render(art, cell) {
  if (art.rows.length !== ROWS || art.rows.some((r) => r.length !== COLS)) {
    throw new Error('every icon is 24x16 cells');
  }
  const w = COLS * cell, h = ROWS * cell;
  const color = Buffer.alloc(w * h * 2), alpha = Buffer.alloc(w * h);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const ch = art.rows[Math.floor(y / cell)][Math.floor(x / cell)];
      if (ch === '.') continue;
      const c = art.palette[ch];
      if (c === undefined) throw new Error(`no colour for '${ch}'`);
      color.writeUInt16LE(rgb565(c), (y * w + x) * 2);
      alpha[y * w + x] = 0xff;
    }
  }
  return { w, h, bytes: Buffer.concat([color, alpha]) };
}

function array(name, macro, img) {
  const lines = [];
  for (let i = 0; i < img.bytes.length; i += 24) {
    const row = [...img.bytes.subarray(i, i + 24)].map((b) => '0x' + b.toString(16).toUpperCase().padStart(2, '0'));
    lines.push('    ' + row.join(',') + ',');
  }
  return [
    `#define ${macro}_W ${img.w}`,
    `#define ${macro}_H ${img.h}`,
    `// RGB565A8: ${img.w * img.h} RGB565 pixels (little-endian) followed by ${img.w * img.h} alpha bytes`,
    `static const uint8_t ${name}[${img.bytes.length}] = {`,
    ...lines,
    '};',
    '',
  ].join('\n');
}

const out = [
  '#pragma once',
  '#include <stdint.h>',
  '',
  '// Corner icons for the agents that aren\'t Claude: Codex (a terminal with its',
  '// `>_` prompt) and Cursor (a mouse pointer). Original pixel art on the corner',
  '// Clawd\'s 24x16-cell grid at 3 px/cell (large) and 2 px/cell (small), so each',
  '// fills his seat. Generated by tools/agent_icons.js; edit the art there.',
  '',
];
for (const [name, art] of [['codex', CODEX], ['cursor', CURSOR]]) {
  const macro = 'AGENT_' + name.toUpperCase();
  out.push(array(`agent_${name}_data`, macro, render(art, 3)));
  out.push(array(`agent_${name}_small_data`, macro + '_SMALL', render(art, 2)));
}
const dest = path.join(__dirname, '..', 'firmware', 'src', 'agent_icons.h');
fs.writeFileSync(dest, out.join('\n'));
console.log(`wrote ${path.relative(process.cwd(), dest)}`);
